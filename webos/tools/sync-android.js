// Takes from the Android app what both apps share, so they look and read the same:
// its string resources become app/strings.js, its backdrop and logo are copied to app/img/.
// node tools/sync-android.js   (runs before `npm run dev` and every `npm run package`)
'use strict';

const fs = require('fs');
const path = require('path');

const RES = path.join(__dirname, '..', '..', 'app', 'src', 'main', 'res');
const OUT = path.join(__dirname, '..', 'app', 'strings.js');
const IMAGES = ['drawable-nodpi/backdrop_default.jpg', 'drawable-nodpi/logo_lockup.png'];

function unescape(s) {
    return s.trim()
        .replace(/^"(.*)"$/s, '$1')
        .replace(/\\n/g, '\n').replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\@/g, '@').replace(/\\\?/g, '?')
        .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&');
}

function parse(file) {
    const xml = fs.readFileSync(file, 'utf8');
    const out = {};
    for (const m of xml.matchAll(/<string name="([^"]+)"[^>]*>([\s\S]*?)<\/string>/g)) out[m[1]] = unescape(m[2]);
    for (const m of xml.matchAll(/<plurals name="([^"]+)">([\s\S]*?)<\/plurals>/g)) {
        const forms = {};
        for (const i of m[2].matchAll(/<item quantity="([^"]+)">([\s\S]*?)<\/item>/g)) forms[i[1]] = unescape(i[2]);
        out[m[1]] = forms;
    }
    return out;
}

const strings = { en: parse(path.join(RES, 'values', 'strings.xml')), ru: parse(path.join(RES, 'values-ru', 'strings.xml')) };
fs.writeFileSync(OUT, '// Generated by tools/sync-android.js from app/src/main/res/values*/strings.xml. Do not edit.\n' +
    'window.STRINGS = ' + JSON.stringify(strings, null, 1) + ';\n');
for (const image of IMAGES) fs.copyFileSync(path.join(RES, image), path.join(__dirname, '..', 'app', 'img', path.basename(image)));
console.log('strings.js: ' + Object.keys(strings.en).length + ' en, ' + Object.keys(strings.ru).length + ' ru; images: ' + IMAGES.length);
